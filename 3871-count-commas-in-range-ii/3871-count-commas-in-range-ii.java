import java.math.BigInteger;
class Solution {
    public long countCommas(long n) {
        if(n<1000L){
            return 0;
        }
        else if(n/1000L<1000L){
            return (n-1000L+1);
        }
        else if(n/1000000L<1000L){
            return (2L*(n-1000000L+1))+(1000000L-1000L);
        }
        else if(n/1000000000L<1000L){
            return (3L*(n-1000000000L+1))+(2L*(1000000000L-1000000L))+(1000000L-1000L);
        }
        else if(n/1000000000000L<1000L){
            return (4L*(n-1000000000000L+1))+(3L*(1000000000000L-1000000000L))+(2L*(1000000000L-1000000L))+(1000000L-1000L);   
        }
        else if(n/1000000000000000L<1000L){
            return (5L*(n-1000000000000000L+1))+(4L*(1000000000000000L-1000000000000L))+(3L*(1000000000000L-1000000000L))+(2L*(1000000000L-1000000L))+(1000000L-1000L);
            
        }
        return 0;
    }
}